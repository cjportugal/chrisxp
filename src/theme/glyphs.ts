  '#': '#101010',
  o: '#f2f1ea',
  c: '#3fc1ff',
  m: '#ff4fd8',
  y: '#ffe24a',
  b: '#1b45c9',
  w: '#ffffff',
  s: '#c0c0c0',
  g: '#808080',
  n: '#000080',
  B: '#0000ff',
