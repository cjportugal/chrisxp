export type GlyphName = keyof typeof GLYPHS;
export type PixelGlyph = readonly string[];

/** Hex values mirror the tokens in theme.css; an SVG data URL cannot read CSS variables. */
const GLYPH_COLORS: Record<string, string> = {
  '#': '#101010',
  o: '#f2f1ea',
  c: '#3fc1ff',
  m: '#ff4fd8',
  y: '#ffe24a',
  b: '#1b45c9',
};

export function glyphSize(glyph: PixelGlyph): { width: number; height: number } {
  return { width: glyph[0]?.length ?? 0, height: glyph.length };
}

const svgCache = new WeakMap<PixelGlyph, string>();

/** Render a glyph as an SVG data URL made of horizontal runs of <rect>, one color per run. */
export function glyphToSvgDataUrl(glyph: PixelGlyph): string {
  const cached = svgCache.get(glyph);
  if (cached) return cached;

  const { width, height } = glyphSize(glyph);
  const rects: string[] = [];
  for (let y = 0; y < height; y++) {
    const row = glyph[y];
    let x = 0;
    while (x < width) {
      const ch = row[x];
      let run = 1;
      while (x + run < width && row[x + run] === ch) run++;
      const fill = GLYPH_COLORS[ch];
      if (fill) rects.push(`<rect x='${x}' y='${y}' width='${run}' height='1' fill='${fill}'/>`);
      x += run;
    }
  }

  const svg =
    `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 ${width} ${height}' width='${width}' height='${height}' shape-rendering='crispEdges'>` +
    rects.join('') +
    '</svg>';
  const url = `data:image/svg+xml,${encodeURIComponent(svg)}`;
  svgCache.set(glyph, url);
  return url;
}
